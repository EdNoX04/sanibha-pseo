"""Persistent state (SQLite).

Why a database instead of "just write files": a scheduled job needs memory between runs.
The store answers
  * has this keyword already been published, and from which inputs? (input_hash -> skip or regenerate)
  * what does the rest of the corpus look like? (shingles + embeddings for duplicate checks
    against ALL pages ever published, not just the ones in this run)
  * what happened in each run? (runs + events tables: the audit trail behind alerts)
SQLite is enough for thousands of pages; the interface is small enough to swap for Postgres.
"""
from __future__ import annotations

import json
import sqlite3
import threading
import time
from pathlib import Path

import numpy as np

SCHEMA = """
CREATE TABLE IF NOT EXISTS pages (
    slug          TEXT PRIMARY KEY,
    keyword       TEXT NOT NULL,
    app_id        TEXT NOT NULL,
    status        TEXT NOT NULL,          -- passed | quarantined | failed | merged
    input_hash    TEXT,
    record_json   TEXT,
    brief_json    TEXT,
    content_json  TEXT,
    body_text     TEXT,
    shingles      BLOB,
    embedding     BLOB,
    faq_embeddings BLOB,                  -- one row per FAQ question (semantic FAQ dedupe)
    qa_json       TEXT,
    judge_json    TEXT,
    attempts      INTEGER DEFAULT 0,
    error         TEXT,
    created_at    REAL,
    updated_at    REAL
);
CREATE TABLE IF NOT EXISTS runs (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    started_at  REAL,
    finished_at REAL,
    status      TEXT,
    stats_json  TEXT
);
CREATE TABLE IF NOT EXISTS events (
    run_id  INTEGER,
    ts      REAL,
    slug    TEXT,
    stage   TEXT,
    level   TEXT,
    message TEXT
);
CREATE INDEX IF NOT EXISTS idx_pages_status ON pages(status);
CREATE TABLE IF NOT EXISTS embed_cache (
    key  TEXT PRIMARY KEY,      -- sha1(model + text)
    vec  BLOB
);
"""


def _decode_matrix(blob: bytes | None) -> np.ndarray | None:
    if not blob:
        return None
    dim = int(np.frombuffer(blob[:4], dtype=np.int32)[0])
    return np.frombuffer(blob[4:], dtype=np.float32).reshape(-1, dim)


class Store:
    def __init__(self, path: Path):
        path.parent.mkdir(parents=True, exist_ok=True)
        self.db = sqlite3.connect(path, check_same_thread=False)
        self.db.row_factory = sqlite3.Row
        self.db.executescript(SCHEMA)
        cols = {r[1] for r in self.db.execute("PRAGMA table_info(pages)")}
        if "faq_embeddings" not in cols:  # migrate databases created before this column existed
            self.db.execute("ALTER TABLE pages ADD COLUMN faq_embeddings BLOB")
            self.db.commit()
        self.run_id: int | None = None
        self.lock = threading.RLock()  # pages can be generated by several worker threads

    # ------------------------------------------------------------------ runs / events
    def start_run(self) -> int:
        # only called while holding the run lock, so any run still marked 'running' was killed
        with self.lock:
            self.db.execute("UPDATE runs SET status='aborted' WHERE status='running'")
            cur = self.db.execute("INSERT INTO runs(started_at, status) VALUES (?, 'running')", (time.time(),))
            self.db.commit()
            self.run_id = cur.lastrowid
            return self.run_id

    def finish_run(self, status: str, stats: dict) -> None:
        with self.lock:
            self.db.execute("UPDATE runs SET finished_at=?, status=?, stats_json=? WHERE id=?",
                            (time.time(), status, json.dumps(stats), self.run_id))
            self.db.commit()

    def event(self, slug: str | None, stage: str, level: str, message: str) -> None:
        with self.lock:
            self._event(slug, stage, level, message)

    def _event(self, slug, stage, level, message) -> None:
        self.db.execute("INSERT INTO events VALUES (?,?,?,?,?,?)",
                        (self.run_id, time.time(), slug, stage, level, message))
        self.db.commit()

    def recent_runs(self, n: int = 10) -> list[dict]:
        with self.lock:
            rows = self.db.execute("SELECT * FROM runs ORDER BY id DESC LIMIT ?", (n,)).fetchall()
            return [dict(r) for r in rows]

    # ------------------------------------------------------------------ embedding cache
    def cached_vectors(self, keys: list[str]) -> dict[str, np.ndarray]:
        if not keys:
            return {}
        with self.lock:
            out = {}
            for i in range(0, len(keys), 500):
                chunk = keys[i:i + 500]
                q = ",".join("?" for _ in chunk)
                for r in self.db.execute(f"SELECT key, vec FROM embed_cache WHERE key IN ({q})", chunk):
                    out[r["key"]] = np.frombuffer(r["vec"], dtype=np.float32)
            return out

    def cache_vectors(self, items: dict[str, np.ndarray]) -> None:
        with self.lock:
            self.db.executemany("INSERT OR REPLACE INTO embed_cache VALUES (?, ?)",
                                [(k, np.asarray(v, dtype=np.float32).tobytes()) for k, v in items.items()])
            self.db.commit()

    # ------------------------------------------------------------------ pages
    def get(self, slug: str) -> dict | None:
        with self.lock:
            r = self.db.execute("SELECT * FROM pages WHERE slug=?", (slug,)).fetchone()
            return dict(r) if r else None

    def upsert(self, slug: str, **fields) -> None:
        with self.lock:
            self._upsert(slug, **fields)

    def _upsert(self, slug: str, **fields) -> None:
        now = time.time()
        existing = self.get(slug)
        if "shingles" in fields and fields["shingles"] is not None:
            fields["shingles"] = np.fromiter(fields["shingles"], dtype=np.uint64).tobytes()
        if "embedding" in fields and fields["embedding"] is not None:
            fields["embedding"] = np.asarray(fields["embedding"], dtype=np.float32).tobytes()
        if "faq_embeddings" in fields and fields["faq_embeddings"] is not None:
            arr = np.asarray(fields["faq_embeddings"], dtype=np.float32)
            fields["faq_embeddings"] = np.int32(arr.shape[1]).tobytes() + arr.tobytes()
        for k in ("record_json", "brief_json", "content_json", "qa_json", "judge_json"):
            if k in fields and fields[k] is not None and not isinstance(fields[k], str):
                fields[k] = json.dumps(fields[k])
        if "content_json" in fields:      # updated_at = when the page content last changed
            fields["updated_at"] = now
        if existing:
            cols = ", ".join(f"{k}=?" for k in fields)
            self.db.execute(f"UPDATE pages SET {cols} WHERE slug=?", (*fields.values(), slug))
        else:
            fields.setdefault("created_at", now)
            fields["slug"] = slug
            cols = ", ".join(fields)
            qs = ", ".join("?" for _ in fields)
            self.db.execute(f"INSERT INTO pages({cols}) VALUES ({qs})", tuple(fields.values()))
        self.db.commit()

    def pages(self, status: str | None = None) -> list[dict]:
        with self.lock:
            if status:
                rows = self.db.execute("SELECT * FROM pages WHERE status=? ORDER BY slug", (status,)).fetchall()
            else:
                rows = self.db.execute("SELECT * FROM pages ORDER BY slug").fetchall()
            return [dict(r) for r in rows]

    def corpus(self, exclude: str | None = None) -> list[dict]:
        """Every published page with decoded similarity features."""
        out = []
        for r in self.pages("passed"):
            if r["slug"] == exclude:
                continue
            out.append({
                "slug": r["slug"],
                "body_text": r["body_text"] or "",
                "shingles": set(np.frombuffer(r["shingles"], dtype=np.uint64).tolist()) if r["shingles"] else set(),
                "embedding": np.frombuffer(r["embedding"], dtype=np.float32) if r["embedding"] else None,
                "title": json.loads(r["content_json"])["title"] if r["content_json"] else "",
                "meta": json.loads(r["content_json"])["meta_description"] if r["content_json"] else "",
                "faqs": [f["question"] for f in json.loads(r["content_json"])["faqs"]] if r["content_json"] else [],
                "faq_emb": _decode_matrix(r["faq_embeddings"]),
                "headings": [json.loads(r["content_json"])[k] for k in
                             ("h1", "steps_heading", "alternatives_heading", "tips_heading")] if r["content_json"] else [],
            })
        return out
